"""Port the Bikram Sambat month-length table from the vendored Nepali date-picker.

    python scripts/port_bs_calendar.py          # reads static/vendor/nepali.datepicker.v4.min.js
    python scripts/port_bs_calendar.py path/to/file.js -o app/core/bs_calendar_data.py

The vendor file is minified JavaScript; this script never executes it. It searches the source for
the calendar table - either an object keyed by BS year (``{1970:[31,31,32,...], ...}``) or a list
of 12-number arrays starting at a given year - validates it (12 months of 28-32 days per year,
364-367 days per year, a contiguous year range that covers BS 1970-2099) and writes a Python
data module. The anchor BS 2000-09-17 = AD 1944-01-01 comes from the project brief; the script
checks that the table is consistent with it where it can.

If the file layout is not recognised the script exits with status 2 and a hint: fix
``extract_table`` below rather than typing the numbers by hand - the table must come from the
vendor file so server and browser agree exactly.
"""

from __future__ import annotations

import argparse
import hashlib
import re
import sys
from datetime import date
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
DEFAULT_SOURCE = ROOT / "static" / "vendor" / "nepali.datepicker.v4.min.js"
DEFAULT_OUTPUT = ROOT / "app" / "core" / "bs_calendar_data.py"
ANCHOR_BS = (2000, 9, 17)
ANCHOR_AD = date(1944, 1, 1)
REQUIRED_RANGE = (1970, 2099)

_KEYED_RE = re.compile(r"(?<![\d.])(\d{4})\s*:\s*\[\s*((?:\d{1,2}\s*,\s*){11}\d{1,2})\s*\]")
_ARRAY_RE = re.compile(r"\[\s*((?:\d{1,2}\s*,\s*){11}\d{1,2})\s*\]")


def _months(text: str) -> list[int]:
    return [int(part) for part in re.split(r"\s*,\s*", text.strip())]


def _plausible(months: list[int]) -> bool:
    return len(months) == 12 and all(28 <= m <= 32 for m in months) and 364 <= sum(months) <= 367


def extract_table(source: str) -> dict[int, list[int]]:
    """Return {bs_year: [12 month lengths]} or raise ValueError with a hint."""
    keyed = {int(y): _months(m) for y, m in _KEYED_RE.findall(source)}
    keyed = {y: m for y, m in keyed.items() if _plausible(m) and 1900 <= y <= 2200}
    if len(keyed) >= 100:
        return keyed

    # Fallback: consecutive 12-number arrays; find the start year from a nearby 4-digit number.
    arrays = [(m.start(), _months(m.group(1))) for m in _ARRAY_RE.finditer(source)]
    arrays = [(pos, months) for pos, months in arrays if _plausible(months)]
    if len(arrays) >= 100:
        first_pos = arrays[0][0]
        window = source[max(0, first_pos - 400) : first_pos]
        years = [int(y) for y in re.findall(r"(?<![\d.])(19\d\d|20\d\d|21\d\d)(?![\d.])", window)]
        if years:
            start = years[-1]
            return {start + i: months for i, (_, months) in enumerate(arrays)}
        raise ValueError(
            f"found {len(arrays)} month arrays but no start year nearby; inspect the file around "
            f"offset {first_pos} and extend extract_table()"
        )
    raise ValueError(
        "could not find a BS month table (expected >=100 years of 12 month lengths); "
        "inspect the vendor file and extend extract_table()"
    )


def validate_table(table: dict[int, list[int]]) -> None:
    years = sorted(table)
    if years != list(range(years[0], years[-1] + 1)):
        raise ValueError("year range is not contiguous")
    lo, hi = REQUIRED_RANGE
    if years[0] > lo or years[-1] < hi:
        raise ValueError(f"table covers {years[0]}-{years[-1]}, need at least {lo}-{hi}")
    for year in years:
        if not _plausible(table[year]):
            raise ValueError(f"implausible month lengths for {year}: {table[year]}")
    anchor_year, anchor_month, anchor_day = ANCHOR_BS
    if anchor_year not in table or anchor_day > table[anchor_year][anchor_month - 1]:
        raise ValueError("anchor BS 2000-09-17 does not exist in the table")


def render_module(table: dict[int, list[int]], source: Path, digest: str) -> str:
    lines = [
        '"""Bikram Sambat calendar data - GENERATED, do not edit by hand.',
        "",
        f"Source: {source.name} (sha256 {digest[:16]}...).",
        "Generated by scripts/port_bs_calendar.py.",
        "Re-run the script whenever the vendored date-picker changes so server and browser agree.",
        "",
        "TODO: BS 2082+ month lengths must be checked against the official government calendar.",
        '"""',
        "",
        "from datetime import date",
        "",
        f"ANCHOR_BS = {ANCHOR_BS!r}  # BS 2000-09-17",
        f"ANCHOR_AD = date({ANCHOR_AD.year}, {ANCHOR_AD.month}, {ANCHOR_AD.day})",
        "",
        "BS_MONTH_DAYS: dict[int, tuple[int, ...]] = {",
    ]
    for year in sorted(table):
        months = ", ".join(str(m) for m in table[year])
        lines.append(f"    {year}: ({months}),")
    lines.append("}")
    lines.append("")
    return "\n".join(lines)


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    parser.add_argument("source", nargs="?", type=Path, default=DEFAULT_SOURCE)
    parser.add_argument("-o", "--output", type=Path, default=DEFAULT_OUTPUT)
    args = parser.parse_args(argv)

    if not args.source.exists():
        print(f"error: {args.source} does not exist - add the vendored date-picker first.")
        return 2
    raw = args.source.read_bytes()
    try:
        table = extract_table(raw.decode("utf-8", "replace"))
        validate_table(table)
    except ValueError as exc:
        print(f"error: {exc}")
        return 2
    args.output.write_text(render_module(table, args.source, hashlib.sha256(raw).hexdigest()))
    years = sorted(table)
    print(f"wrote {args.output} ({len(table)} years, BS {years[0]}-{years[-1]})")
    print("now run: make test   (BS round-trip and known-pair tests must pass)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
